#!/usr/bin/env python3
"""
make_trace_wrapper.py - Create LWC_2pass_trace.vhd from the upstream LWC_2pass.vhd.

The copy is identical to the upstream wrapper except for one added, passive
process that writes every signal on the CryptoCore boundary to a text file
on every rising clock edge. Values are sampled at the edge, i.e. the stable
values the core's registers see. Nothing is driven, so the design under test
behaves exactly as the original.

Usage: python3 make_trace_wrapper.py <upstream LWC_2pass.vhd> <output .vhd>
"""
import sys

TRACE = r'''
    -- ===================================================================
    -- ADDED FOR OptimizedHardware golden traces (passive, drives nothing).
    -- One line per rising clock edge, all values sampled at the edge.
    -- Columns: see OptimizedHardware/verif/README section "Trace format".
    -- ===================================================================
    p_core_trace : process(clk)
        file     f   : text open write_mode is "core_trace.txt";
        variable l   : line;
        function c(s : std_logic) return character is
        begin
            case s is
                when '0' | 'L' => return '0';
                when '1' | 'H' => return '1';
                when others    => return 'X';
            end case;
        end function;
    begin
        if rising_edge(clk) then
            -- inputs to the core
            write(l, c(rst));                                  write(l, ' ');
            write(l, to_hstring(key_cipher_in));               write(l, ' ');
            write(l, c(key_valid_cipher_in));                  write(l, ' ');
            write(l, c(key_update_cipher_in));                 write(l, ' ');
            write(l, to_hstring(bdi_cipher_in));               write(l, ' ');
            write(l, c(bdi_valid_cipher_in));                  write(l, ' ');
            write(l, to_hstring(bdi_pad_loc_cipher_in));       write(l, ' ');
            write(l, to_hstring(bdi_valid_bytes_cipher_in));   write(l, ' ');
            write(l, to_hstring('0' & bdi_size_cipher_in));    write(l, ' ');
            write(l, c(bdi_eot_cipher_in));                    write(l, ' ');
            write(l, c(bdi_eoi_cipher_in));                    write(l, ' ');
            write(l, to_hstring(bdi_type_cipher_in));          write(l, ' ');
            write(l, c(decrypt_cipher_in));                    write(l, ' ');
            write(l, c(hash_cipher_in));                       write(l, ' ');
            write(l, c(bdo_ready_cipher_out));                 write(l, ' ');
            write(l, c(msg_auth_ready));                       write(l, ' ');
            write(l, to_hstring(fdi_data));                    write(l, ' ');
            write(l, c(fdi_valid));                            write(l, ' ');
            write(l, c(fdo_ready));                            write(l, ' ');
            -- outputs of the core
            write(l, c(key_ready_cipher_in));                  write(l, ' ');
            write(l, c(bdi_ready_cipher_in));                  write(l, ' ');
            write(l, to_hstring(bdo_cipher_out));              write(l, ' ');
            write(l, c(bdo_valid_cipher_out));                 write(l, ' ');
            write(l, to_hstring(bdo_type_cipher_out));         write(l, ' ');
            write(l, to_hstring(bdo_valid_bytes_cipher_out));  write(l, ' ');
            write(l, c(end_of_block_cipher_out));              write(l, ' ');
            write(l, c(msg_auth_valid));                       write(l, ' ');
            write(l, c(msg_auth));                             write(l, ' ');
            write(l, c(fdi_ready));                            write(l, ' ');
            write(l, to_hstring(fdo_data));                    write(l, ' ');
            write(l, c(fdo_valid));
            writeline(f, l);
        end if;
    end process;

end structure;
'''


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    src = open(sys.argv[1]).read()
    tail = src.rstrip().rsplit("\n", 1)
    if tail[1].strip().lower() != "end structure;":
        sys.exit("Unexpected end of LWC_2pass.vhd; upstream file changed?")
    out = tail[0] + "\n" + TRACE
    out = out.replace("use ieee.std_logic_1164.all;",
                      "use ieee.std_logic_1164.all;\nuse std.textio.all;", 1)
    with open(sys.argv[2], "w") as f:
        f.write("-- GENERATED by OptimizedHardware/verif/golden/make_trace_wrapper.py\n"
                "-- from hardware/LWC_rtl/LWC_2pass.vhd. Do not edit.\n")
        f.write(out)


if __name__ == "__main__":
    main()
